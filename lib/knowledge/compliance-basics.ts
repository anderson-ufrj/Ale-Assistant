export function getKnowledgeByCategory(category: string) {
  return complianceKnowledge.filter(item => item.category === category);
}

export function searchKnowledge(query: string): typeof complianceKnowledge {
  const lowerQuery = query.toLowerCase();
  return complianceKnowledge
    .filter(item =>
      item.title.toLowerCase().includes(lowerQuery) ||
      item.content.toLowerCase().includes(lowerQuery) ||
      item.tags.some(tag => tag.toLowerCase().includes(lowerQuery))
    )
    .sort((a, b) => b.relevance - a.relevance);
}

export function getAllKnowledge() {
  return complianceKnowledge;
}
